"""The integrations. See `__init__.py` for the format. Fields: params[].in = path | query | body | header ;
key "*" merges an object parameter into the body (or the query) ; body_defaults are fixed body fields ;
fail_if = {path, is | present, message_path} turns a 200 answer that carries an error into a failed step."""


def p(
    name,
    label,
    where="body",
    type_="string",
    required=False,
    example=None,
    key=None,
    default=None,
    help_=None,
    raw=None,
):
    out = {"name": name, "label": label, "in": where, "type": type_, "required": required}
    for k, v in (("example", example), ("key", key), ("default", default), ("help", help_), ("raw", raw)):
        if v is not None:
            out[k] = v
    return out


def op(oid, name, description, method, path, params=(), **extra):
    return {
        "id": oid,
        "name": name,
        "description": description,
        "method": method,
        "path": path,
        "params": list(params),
        **extra,
    }


def svc(slug, name, category, description, kind, config, operations, setup=""):
    return {
        "slug": slug,
        "name": name,
        "category": category,
        "description": description,
        "connection": {"kind": kind, "config": config, "setup": setup},
        "operations": operations,
    }


