CONFIG_FIELDS = {
    Connection.Kind.HTTP_BEARER: ("base_url",),
    Connection.Kind.API_KEY: ("base_url", "in", "name", "prefix"),
    Connection.Kind.BASIC: ("base_url", "username"),
    Connection.Kind.OAUTH2_CLIENT: ("base_url", "token_url", "client_id", "scope"),
    Connection.Kind.OAUTH2_CODE: ("base_url", "authorize_url", "token_url", "client_id", "scope"),
    Connection.Kind.IMAP: ("host", "port", "username", "folder"),
    Connection.Kind.POSTGRES: ("host", "port", "database", "username", "sslmode"),
    Connection.Kind.MYSQL: ("host", "port", "database", "username", "tls"),
    Connection.Kind.LDAP: ("host", "port", "bind_dn", "base_dn", "tls"),
    Connection.Kind.SFTP: ("host", "port", "username", "host_key_sha256"),
    Connection.Kind.SMTP: ("host", "port", "username", "tls", "from_address", "from_name"),
    Connection.Kind.AWS_SIGV4: ("base_url", "access_key_id", "region", "service"),
}
URL_FIELDS = ("base_url", "token_url", "authorize_url")


def _check_config(kind, config, dynamic: bool = False):
    """`dynamic`: the user name comes from Vault together with the password, so it is not asked for here."""
    wanted = CONFIG_FIELDS.get(kind)
    if wanted is not None:
        for key in wanted:
            if (
                key
                in (
                    "scope",
                    "name",
                    "in",
                    "prefix",
                    "port",
                    "folder",
                    "service",
                    "sslmode",
                    "tls",
                    "port",
                    "host_key_sha256",
                    "from_name",
                )
                or key == "description"
                or (dynamic and key in ("username", "bind_dn"))
            ):
                continue
            if not str(config.get(key) or "").strip():
                raise serializers.ValidationError(
                    {"config": f"Le paramètre « {key} » est requis pour ce type de connexion."}
                )
        if kind == Connection.Kind.SMTP:
            from runs import smtp_node

            try:
                smtp_node.check_connection_config(config)
            except smtp_node.SmtpStepError as exc:
                raise serializers.ValidationError({"config": exc.message}) from None
        if kind == Connection.Kind.API_KEY and config.get("in", "header") not in ("header", "query"):
            raise serializers.ValidationError({"config": "« in » : header ou query."})
        for key in URL_FIELDS:
            if config.get(key):
                try:
                    netsec.validate_url(config[key])
                except netsec.UnsafeURL as exc:
                    raise serializers.ValidationError({"config": f"{key} : {exc}"}) from None
    keep = (*(wanted or ()), "description")
    return {k: v for k, v in config.items() if k in keep and isinstance(v, str)}


class ConnectionListCreateView(APIView):
    serializer_class = ConnectionCreateSerializer

    def get(self, request, workspace):
        ws = get_workspace(request.user, workspace, VIEW)
        rows = Connection.objects.filter(workspace=ws).select_related("secret", "environment").order_by("name", "id")
        return Response({"results": ConnectionSerializer(rows, many=True).data})

    @transaction.atomic
    def post(self, request, workspace):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        ser = ConnectionCreateSerializer(data=request.data)
        ser.is_valid(raise_exception=True)
        d = ser.validated_data
        env = Environment.objects.filter(workspace=ws, kind=d["environment"]).first() if d.get("environment") else None
        if d.get("environment") and env is None:
            raise serializers.ValidationError({"environment": "Environnement inconnu."})
        if Connection.objects.filter(workspace=ws, name=d["name"], environment=env).exists():
            raise serializers.ValidationError({"name": "Une connexion de ce nom existe déjà pour cet environnement."})
        vault_ref = d.get("vault") or {}
        external_secret = d.get("secret_provider") == Secret.Provider.VAULT
        dynamic = external_secret and vault_ref.get("mode") == Secret.VaultMode.DYNAMIC
        config = _check_config(d["kind"], d.get("config", {}), dynamic)
        secret = None
        if external_secret or d.get("secret_value"):
            secret_name = f"{d['name']}-{(env.kind if env else 'all')}"
            if Secret.objects.filter(workspace=ws, name=secret_name).exists():
                raise serializers.ValidationError({"name": "Un secret de ce nom existe déjà."})
            secret = build_secret(
                ws,
                request.user,
                secret_name,
                d.get("secret_provider", "internal"),
                d.get("secret_value", ""),
                vault_ref,
            )
        elif d.get("secret"):
            secret = Secret.objects.filter(workspace=ws, name=d["secret"]).first()
            if secret is None:
                raise serializers.ValidationError({"secret": "Secret inconnu dans cet espace."})
        conn = Connection.objects.create(
            workspace=ws,
            name=d["name"],
            label=d["label"],
            kind=d["kind"],
            config=config,
            secret=secret,
            environment=env,
            created_by=request.user,
        )
        record("connection.create", actor=request.user, workspace=ws, target=conn, kind=conn.kind)
        return Response(ConnectionSerializer(conn).data, status=201)


