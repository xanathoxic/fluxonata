OAUTH_SALT = "fluxonata.oauth.state"

MAX_SECRET = 8192


class VaultRefSerializer(serializers.Serializer):
    """Where an external secret lives. `managed`: Fluxonata writes it in its own Vault area (a `value` is required);
    `reference`: something that already exists; `dynamic`: credentials generated by a Vault engine (database...)."""

    mode = serializers.ChoiceField(choices=[m.value for m in Secret.VaultMode], default=Secret.VaultMode.MANAGED)
    mount = serializers.CharField(max_length=80, required=False, allow_blank=True, default="")
    path = serializers.CharField(max_length=200, required=False, allow_blank=True, default="")
    key = serializers.CharField(max_length=80, required=False, allow_blank=True, default="")
    version = serializers.IntegerField(min_value=1, required=False, allow_null=True, default=None)


class SecretCreateSerializer(serializers.Serializer):
    name = serializers.SlugField(max_length=60)
    value = serializers.CharField(
        max_length=MAX_SECRET, trim_whitespace=False, write_only=True, required=False, allow_blank=True
    )
    provider = serializers.ChoiceField(choices=[p.value for p in Secret.Provider], default=Secret.Provider.INTERNAL)
    vault = VaultRefSerializer(required=False)


def vault_failure(exc: external.ExternalVaultError):
    """A Vault problem seen by the person who made the request: a field error, never a server error."""
    return serializers.ValidationError({"vault": exc.message, "code": exc.code})


@transaction.atomic
def build_secret(ws, user, name: str, provider: str, value: str, vault: dict | None) -> Secret:
    """Creates (and saves) a secret of either provider. For an external one nothing but the reference is stored here.
    Atomic: a refusal from Vault leaves no half-made secret behind."""
    s = Secret(workspace=ws, name=name, created_by=user)
    if provider != Secret.Provider.VAULT:
        if not value:
            raise serializers.ValidationError({"value": "Valeur requise."})
        s.set_value(value)
        s.save()
        return s
    vault = vault or {}
    mode = vault.get("mode") or Secret.VaultMode.MANAGED
    try:
        cfg = external.require_enabled()
        if mode == Secret.VaultMode.MANAGED:
            if not value:
                raise serializers.ValidationError({"value": "Valeur requise."})
            external.configure_managed(s, cfg)
            s.set_value(value)
            s.save()
        else:
            external.configure_reference(
                s,
                cfg,
                mode,
                vault.get("mount") or cfg.kv_mount,
                vault.get("path"),
                vault.get("key", ""),
                vault.get("version"),
            )
            s.save()
            if value:
                s.set_value(value)  # writes through the grant (read-only grants refuse it)
            external.check(s)  # fail now, with a clear message, rather than at the first run
    except external.ExternalVaultError as exc:
        raise vault_failure(exc) from None
    return s


def secret_row(s: Secret) -> dict:
    return {
        "name": s.name,
        "created_at": s.created_at,
        "rotated_at": s.rotated_at,
        "key_id": s.key_id,
        "used_by": s.n_connections if hasattr(s, "n_connections") else s.connections.count(),
        "provider": s.provider,
        "vault_mode": s.vault_mode,
        "vault_mount": s.vault_mount,
        "vault_path": s.vault_path,
        "vault_key": s.vault_key,
        "vault_version": s.vault_version,
    }


class SecretListView(APIView):
    serializer_class = SecretCreateSerializer

    def get(self, request, workspace):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        rows = Secret.objects.filter(workspace=ws).annotate(n_connections=Count("connections")).order_by("name", "id")
        return Response({"results": [secret_row(s) for s in rows]})

    def post(self, request, workspace):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        ser = SecretCreateSerializer(data=request.data)
        ser.is_valid(raise_exception=True)
        if Secret.objects.filter(workspace=ws, name=ser.validated_data["name"]).exists():
            raise serializers.ValidationError({"name": "Ce secret existe déjà."})
        d = ser.validated_data
        s = build_secret(ws, request.user, d["name"], d["provider"], d.get("value", ""), d.get("vault"))
        record("secret.create", actor=request.user, workspace=ws, target=s, provider=s.provider, mode=s.vault_mode)
        return Response({"name": s.name, "provider": s.provider}, status=201)


class SecretDetailView(APIView):
    def put(self, request, workspace, name):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        s = Secret.objects.filter(workspace=ws, name=name).first()
        value = request.data.get("value")
        if s is None:
            raise Http404()
        if not isinstance(value, str) or not value or len(value) > MAX_SECRET:
            raise serializers.ValidationError({"value": "Valeur requise."})
        try:
            s.set_value(value)
        except external.ExternalVaultError as exc:
            raise vault_failure(exc) from None
        s.rotated_at = timezone.now()
        s.save()
        record("secret.replace", actor=request.user, workspace=ws, target=s, provider=s.provider)
        return Response(status=204)

    def delete(self, request, workspace, name):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        s = Secret.objects.filter(workspace=ws, name=name).first()
        if s is None:
            raise Http404()
        if s.connections.exists():
            raise serializers.ValidationError({"name": "Ce secret est utilisé par une connexion."})
        if s.webhooks.exists():
            raise serializers.ValidationError({"name": "Ce secret signe un webhook."})
        purge = str(request.query_params.get("purge", "")).lower() in ("1", "true", "oui")
        try:
            external.destroy(s, purge)  # leases ended; with ?purge=1 what Fluxonata wrote in Vault is deleted too
        except external.ExternalVaultError as exc:
            raise vault_failure(exc) from None
        record("secret.delete", actor=request.user, workspace=ws, target=s, provider=s.provider, purged=purge)
        s.delete()
        return Response(status=204)


class SecretTestView(APIView):
    """Can the secret be read right now? Answers with the names of its fields, never a value."""

    def post(self, request, workspace, name):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        s = Secret.objects.filter(workspace=ws, name=name).first()
        if s is None:
            raise Http404()
        if not s.is_external:
            return Response({"ok": True, "fields": [], "mode": "internal"})
        try:
            result = external.check(s)
        except external.ExternalVaultError as exc:
            return Response({"ok": False, "code": exc.code, "message": exc.message})
        record("secret.test", actor=request.user, workspace=ws, target=s, provider=s.provider)
        return Response(result)


class WorkspaceVaultView(APIView):
    """What this workspace can do with the external vault (read-only view for the people who manage its connections)."""

    def get(self, request, workspace):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        cfg = external.config()
        if not external.available():
            return Response({"available": False})
        return Response(
            {
                "available": True,
                "mount": cfg.kv_mount,
                "own_prefix": external.own_prefix(cfg, ws),
                "grants": list(ws.vault_grants.order_by("pattern").values("pattern", "writable")),
            }
        )


