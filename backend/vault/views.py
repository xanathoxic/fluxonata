class ConnectionTestView(APIView):
    """Tests a connection without ever revealing the secret (neither in the response, the log nor the audit)."""

    def post(self, request, workspace, pk):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        conn = Connection.objects.select_related("secret").filter(workspace=ws, pk=pk).first()
        if conn is None:
            raise Http404()
        ok, message = self._run(conn)
        conn.last_test_ok, conn.last_test_at, conn.last_test_message = ok, timezone.now(), message[:300]
        conn.save(update_fields=["last_test_ok", "last_test_at", "last_test_message"])
        record("connection.test", actor=request.user, workspace=ws, target=conn, ok=ok)
        return Response({"ok": ok, "message": message})

    @staticmethod
    def _run(conn) -> tuple[bool, str]:
        if conn.secret is None:
            return False, "Aucun secret n'est associé à cette connexion."
        try:
            conn.secret.reveal()
        except external.ExternalVaultError as exc:
            return False, exc.message
        except Exception:  # noqa: BLE001
            return False, "Le secret est illisible (clé absente ou donnée corrompue)."
        if conn.kind not in auth.HTTP_KINDS:
            return True, "Le secret est présent et déchiffrable."
        try:
            creds = auth.credentials(conn)
        except auth.AuthError as exc:
            return False, exc.message
        url = conn.config["base_url"]
        if creds.query:
            url += ("&" if "?" in url else "?") + urlencode(creds.query)
        try:
            status, _, _ = netsec.safe_request("GET", url, headers=creds.headers, timeout=5)
        except netsec.UnsafeURL as exc:
            return False, f"Adresse refusée : {exc}"
        except OSError:
            return False, "Le service n'a pas répondu (réseau, délai dépassé ou certificat refusé)."
        if 200 <= status < 300:
            return True, f"Le service a répondu (HTTP {status})."
        if status in (401, 403):
            return False, f"Le service a refusé les identifiants (HTTP {status})."
        return False, f"Réponse inattendue du service (HTTP {status})."


def _redirect_uri(request) -> str:
    base = getattr(settings, "ORCH_PUBLIC_URL", "").rstrip("/")
    return f"{base}/api/v1/oauth/callback/" if base else request.build_absolute_uri("/api/v1/oauth/callback/")


class ConnectionOAuthStartView(APIView):
    """Starts the authorization of an « OAuth2, autorisation par une personne » connection: returns the address to open."""

    def post(self, request, workspace, pk):
        ws = get_workspace(request.user, workspace, MANAGE_CONNECTIONS)
        conn = Connection.objects.filter(workspace=ws, pk=pk, kind=Connection.Kind.OAUTH2_CODE).first()
        if conn is None:
            raise Http404()
        state = signing.dumps({"c": conn.pk, "u": request.user.pk}, salt=OAUTH_SALT)
        cfg = conn.config
        query = {
            "response_type": "code",
            "client_id": cfg["client_id"],
            "redirect_uri": _redirect_uri(request),
            "state": state,
        }
        if cfg.get("scope"):
            query["scope"] = cfg["scope"]
        sep = "&" if "?" in cfg["authorize_url"] else "?"
        record("connection.oauth_start", actor=request.user, workspace=ws, target=conn)
        return Response(
            {"authorize_url": cfg["authorize_url"] + sep + urlencode(query), "redirect_uri": _redirect_uri(request)}
        )


class OAuthCallbackView(APIView):
    """Return address of the authorization: the signed `state` identifies the connection and the person, the code is
    exchanged server-side (the token never reaches the browser)."""

    authentication_classes: list = []
    permission_classes = [AllowAny]

    def get(self, request):
        def back(result):
            return HttpResponseRedirect(f"/connections?oauth={result}")

        try:
            data = signing.loads(request.query_params.get("state", ""), salt=OAUTH_SALT, max_age=600)
        except signing.BadSignature:
            return back("invalid")
        conn = Connection.objects.select_related("secret", "workspace").filter(pk=data["c"]).first()
        user = get_user_model().objects.filter(pk=data["u"]).first()
        if conn is None or user is None or not has_perm(user, conn.workspace, MANAGE_CONNECTIONS):
            return back("invalid")
        code = request.query_params.get("code")
        if not code:
            return back("denied")
        try:
            auth.exchange_code(conn, code, _redirect_uri(request), user)
        except auth.AuthError:
            return back("error")
        record("connection.oauth_authorized", actor=user, workspace=conn.workspace, target=conn)
        return back("ok")
